// Command gen turns the vendored Message Data Model OpenAPI schema into Go types.
//
// The MDM is not reverse-engineered: Sublime publishes the full OpenAPI definition inlined
// in the markdown of their API reference. mdm/mdm.openapi.json is that document, and this
// generator is what keeps mdm/types.gen.go honest to it. Hand-transcribing 44 schemas would
// have guaranteed drift; regenerating makes an upstream change a diff instead of an
// archaeology exercise.
//
// Usage:
//
//	go run ./mdm/gen -in mdm/mdm.openapi.json -out mdm/types.gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"slices"
	"sort"
	"strings"
	"unicode"
)

// schemaPrefixes are the namespaces upstream puts on its components. They are stripped:
// within package mdm, "Mdm_serviceAttachment" says nothing that "Attachment" does not.
var schemaPrefixes = []string{
	"Mdm_service",
	"Enrichment_types",
	"Link_analysis_types",
	"Handler_types",
}

// renames map upstream component names onto the names MQL's own documentation uses.
//
// Rules navigate fields rather than naming types, so this is about readability: someone
// reading a diagnostic about file.explode should see the type the docs call
// FileExplodeOutput, not the name of the service that happens to produce it.
var renames = map[string]string{
	"StrelkaResponse":                   "FileExplodeOutput",
	"StrelkaScan":                       "FileScan",
	"Handler_typesLinkAnalysisResponse": "LinkAnalysisOutput",
	"FfiJSON":                           "JSONValue",
}

type document struct {
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

type schema struct {
	Type                 string             `json:"type"`
	Description          string             `json:"description"`
	Required             []string           `json:"required"`
	Properties           map[string]*schema `json:"properties"`
	Items                *schema            `json:"items"`
	Ref                  string             `json:"$ref"`
	Format               string             `json:"format"`
	Enum                 []string           `json:"enum"`
	Nullable             bool               `json:"nullable"`
	AdditionalProperties *schema            `json:"additionalProperties"`
}

func main() {
	in := flag.String("in", "mdm/mdm.openapi.json", "vendored OpenAPI document")
	out := flag.String("out", "mdm/types.gen.go", "generated Go file")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatalf("reading schema: %v", err)
	}
	var doc document
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatalf("parsing schema: %v", err)
	}
	if len(doc.Components.Schemas) == 0 {
		log.Fatalf("%s contains no component schemas", *in)
	}

	src, err := generate(doc.Components.Schemas, *in)
	if err != nil {
		log.Fatalf("generating: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("writing %s: %v", *out, err)
	}
	fmt.Printf("wrote %s (%d schemas)\n", *out, len(doc.Components.Schemas))
}

func generate(schemas map[string]*schema, source string) ([]byte, error) {
	names := make([]string, 0, len(schemas))
	for n := range schemas {
		names = append(names, n)
	}
	sort.Strings(names)

	var body bytes.Buffer

	// Enums first, so the struct fields below can refer to the named types.
	for _, name := range names {
		sc := schemas[name]
		for _, prop := range sortedKeys(sc.Properties) {
			if e := enumNode(sc.Properties[prop]); e != nil {
				writeEnum(&body, goTypeName(name)+goFieldName(prop), e)
			}
		}
	}

	for _, name := range names {
		if err := writeStruct(&body, name, schemas[name]); err != nil {
			return nil, err
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `// SPDX-License-Identifier: AGPL-3.0-only

// Code generated by "go run ./mdm/gen"; DO NOT EDIT.
//
// Source: %s, vendored from Sublime Security's published API reference.

package mdm
`, source)
	if bytes.Contains(body.Bytes(), []byte("time.Time")) {
		b.WriteString("\nimport \"time\"\n")
	}
	b.Write(body.Bytes())

	src, err := format.Source(b.Bytes())
	if err != nil {
		// Emit the unformatted source alongside the error: a syntax bug in the generator is
		// far easier to find by reading what it produced than by reading the generator.
		return nil, fmt.Errorf("%w\n--- generated source ---\n%s", err, b.String())
	}
	return src, nil
}

// enumNode returns the schema node carrying an enumeration for a property, or nil if there
// is none. The enum sits on the property itself for scalars, but on the element schema for
// arrays such as IPTranslation.encoders — both name a single Go type after the property.
func enumNode(p *schema) *schema {
	switch {
	case len(p.Enum) > 0:
		return p
	case p.Type == "array" && p.Items != nil && len(p.Items.Enum) > 0:
		return p.Items
	default:
		return nil
	}
}

func writeEnum(b *bytes.Buffer, typeName string, p *schema) {
	fmt.Fprintf(b, "\n// %s enumerates the values upstream documents for this field.\n", typeName)
	if p.Description != "" {
		fmt.Fprintf(b, "//\n// %s\n", wrapComment(p.Description))
	}
	fmt.Fprintf(b, "//\n// Unknown values are preserved rather than rejected: a message that arrives with a\n")
	fmt.Fprintf(b, "// value we do not recognise is still a message we must evaluate rules against.\n")
	fmt.Fprintf(b, "type %s string\n\nconst (\n", typeName)
	for _, v := range p.Enum {
		fmt.Fprintf(b, "\t%s%s %s = %q\n", typeName, enumSuffix(v), typeName, v)
	}
	b.WriteString(")\n")
}

func writeStruct(b *bytes.Buffer, schemaName string, sc *schema) error {
	name := goTypeName(schemaName)
	b.WriteString("\n")
	if sc.Description != "" {
		fmt.Fprintf(b, "// %s %s\n", name, lowerFirstWord(wrapComment(sc.Description)))
	} else {
		fmt.Fprintf(b, "// %s is the %s component of the Message Data Model.\n", name, schemaName)
	}
	fmt.Fprintf(b, "type %s struct {\n", name)

	required := sc.Required
	for _, prop := range sortedKeys(sc.Properties) {
		p := sc.Properties[prop]
		typ, err := goType(name, prop, p, slices.Contains(required, prop))
		if err != nil {
			return fmt.Errorf("%s.%s: %w", schemaName, prop, err)
		}
		if p.Description != "" {
			fmt.Fprintf(b, "\n\t// %s\n", wrapComment(p.Description))
		}
		// The JSON tag carries the MQL field name. The type checker resolves paths such as
		// sender.email.domain.root_domain through these tags, so they are load-bearing: a
		// wrong tag is an unresolvable field, not a cosmetic issue.
		fmt.Fprintf(b, "\t%s %s `json:\"%s,omitempty\"`\n", goFieldName(prop), typ, prop)
	}
	b.WriteString("}\n")
	return nil
}

// goType maps one schema property onto a Go type.
//
// Optionality is represented with pointers rather than zero values, because MQL draws a
// distinction the zero value cannot: length("") is 0 but length(null) is null, and rules
// test `headers.in_reply_to is null` several hundred times across the public corpus. A
// field is a pointer unless the schema marks it required and non-nullable.
func goType(structName, prop string, p *schema, required bool) (string, error) {
	optional := p.Nullable || !required

	// Composites are nil-able already; an extra pointer would only add a way to be wrong.
	switch {
	case p.Ref != "":
		return "*" + refTypeName(p.Ref), nil

	case p.Type == "array":
		if p.Items == nil {
			return "", fmt.Errorf("array without items")
		}
		elem, err := goType(structName, prop, p.Items, true)
		if err != nil {
			return "", err
		}
		return "[]" + elem, nil

	case p.Type == "object":
		if p.AdditionalProperties == nil {
			return "map[string]any", nil
		}
		val, err := goType(structName, prop, p.AdditionalProperties, true)
		if err != nil {
			return "", err
		}
		return "map[string]" + val, nil
	}

	var base string
	switch p.Type {
	case "string":
		switch p.Format {
		case "date-time":
			base = "time.Time"
		case "base64":
			// Raw bytes, already nil-able, and never something to copy around by value.
			return "[]byte", nil
		default:
			if len(p.Enum) > 0 {
				base = goTypeName(structName) + goFieldName(prop)
			} else {
				base = "string"
			}
		}
	case "integer":
		// All integer widths collapse to int64. MQL exposes a single integer type, so
		// preserving int32 versus int64 here would buy nothing and invite overflow bugs at
		// the boundary between the schema and the evaluator.
		base = "int64"
	case "number":
		base = "float64"
	case "boolean":
		base = "bool"
	default:
		return "", fmt.Errorf("unsupported type %q", p.Type)
	}

	if optional {
		return "*" + base, nil
	}
	return base, nil
}

func refTypeName(ref string) string {
	return goTypeName(ref[strings.LastIndex(ref, "/")+1:])
}

// goTypeName strips the upstream namespace and applies Go initialism conventions.
func goTypeName(schemaName string) string {
	if renamed, ok := renames[schemaName]; ok {
		return renamed
	}
	for _, prefix := range schemaPrefixes {
		if trimmed, found := strings.CutPrefix(schemaName, prefix); found {
			return exportedName(trimmed)
		}
	}
	return exportedName(schemaName)
}

// goFieldName converts a snake_case JSON property to an exported Go field name. Leading
// underscores (_meta, _errors) are dropped; the JSON tag still carries the original.
func goFieldName(prop string) string {
	return exportedName(strings.TrimLeft(prop, "_"))
}

// initialisms that Go style wants fully capitalised. Restricted to the ones that actually
// occur in this schema, so the mapping stays reviewable.
var initialisms = map[string]string{
	"id": "ID", "ip": "IP", "url": "URL", "uri": "URI", "html": "HTML",
	"dkim": "DKIM", "spf": "SPF", "dmarc": "DMARC", "tls": "TLS", "eml": "EML",
	"json": "JSON", "md5": "MD5", "sha1": "SHA1", "sha256": "SHA256",
	"tld": "TLD", "sld": "SLD", "mime": "MIME", "smtp": "SMTP", "ips": "IPs",
	"urls": "URLs", "ids": "IDs", "cc": "CC", "bcc": "BCC", "to": "To",
}

var nonAlphanumeric = regexp.MustCompile(`[^A-Za-z0-9]+`)

func exportedName(s string) string {
	// Upstream names arrive in two shapes: CamelCase for schemas, snake_case for
	// properties. Splitting on non-alphanumerics handles both, plus dotted and hyphenated
	// values that appear in enums.
	parts := nonAlphanumeric.Split(s, -1)
	var b strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		if init, ok := initialisms[strings.ToLower(part)]; ok {
			b.WriteString(init)
			continue
		}
		if isUpperCamel(part) {
			b.WriteString(part)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

// isUpperCamel reports whether a part already looks like CamelCase, so that schema names
// such as "MessageDataModel" survive intact instead of becoming "Messagedatamodel".
func isUpperCamel(s string) bool {
	if !unicode.IsUpper(rune(s[0])) {
		return false
	}
	return strings.ToUpper(s) != s || len(s) == 1
}

// enumSuffix builds a constant suffix from an enum value, which may be anything at all —
// "3gp", "bestguesspass", "application/zip".
func enumSuffix(v string) string {
	name := exportedName(v)
	if name == "" {
		return "Unknown"
	}
	if unicode.IsDigit(rune(name[0])) {
		// Go identifiers cannot start with a digit; "3gp" becomes "N3gp".
		return "N" + name
	}
	return name
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// wrapComment folds a schema description into doc-comment lines, since upstream
// descriptions run to several hundred characters on a single line.
func wrapComment(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	const width = 88
	var lines []string
	for len(s) > width {
		cut := strings.LastIndex(s[:width], " ")
		if cut <= 0 {
			break
		}
		lines = append(lines, s[:cut])
		s = s[cut+1:]
	}
	lines = append(lines, s)
	return strings.Join(lines, "\n\t// ")
}

func lowerFirstWord(s string) string {
	if s == "" {
		return s
	}
	first, rest, _ := strings.Cut(s, " ")
	// Leave acronyms and proper nouns alone; only downcase ordinary sentence openers.
	if strings.ToUpper(first) == first && len(first) > 1 {
		return s
	}
	return strings.ToLower(first[:1]) + first[1:] + " " + rest
}
